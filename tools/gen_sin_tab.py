"""Writes rtl/prim/grv_sin_tab.vh: quarter-wave sine table of grv_sincos (1024 x 17 bits),
T[i] = round(sin(i * pi / 2048) * (2^17 - 1)); T[1024] = 2^17 - 1 is supplied by the logic."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'grvgen'))
from grv.fx import sin_tab
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rtl', 'prim', 'grv_sin_tab.vh')
with open(out, 'w') as f:
    f.write('// generated by tools/gen_sin_tab.py - quarter-wave sine, 1024 x 17 bits\n')
    for i, v in enumerate(sin_tab()):
        f.write(f'tab[{i}] = 17\'d{v};\n')
print('wrote', out)
